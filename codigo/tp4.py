"""#6. GENERACIÓN DE VARIABLES ALEATORIAS POR TRANSFORMADA INVERSA"""

loc_ia, scale_ia = eval_ia.loc[eval_ia['Distribución'] == 'expon', 'Parámetros'].values[0]
