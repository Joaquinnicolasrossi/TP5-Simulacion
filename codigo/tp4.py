"""#5. AJUSTE DE FUNCIONES DE DENSIDAD DE PROBABILIDAD (FDP)"""

df_hosp = df[df['Hospital ID'] == 'HOSP-2'].copy()
datos_ia = df_hosp['IA_min'].dropna().values
datos_ta = df_hosp['TA_min'].dropna().values

DISTRIBUCIONES = ['expon', 'gamma', 'lognorm', 'weibull_min']

def evaluar_ajustes(datos, nombre_variable):
    print(f"\n--- Evaluando ajustes para: {nombre_variable} ---")
    filas = []
    for d_name in DISTRIBUCIONES:
        dist = getattr(stats, d_name)
        params = dist.fit(datos)

        ks_res = stats.kstest(datos, d_name, args=params)

        log_lik = np.sum(dist.logpdf(datos, *params))
        k = len(params)
        n = len(datos)
        aic = 2 * k - 2 * log_lik
        bic = k * np.log(n) - 2 * log_lik

        filas.append({
            'Distribución': d_name,
            'KS Stat (D)': round(ks_res.statistic, 4),
            'p-value': round(ks_res.pvalue, 4),
            'AIC': round(aic, 1),
            'BIC': round(bic, 1),
            'Parámetros': params
        })
    df_eval = pd.DataFrame(filas).sort_values('KS Stat (D)').reset_index(drop=True)
    return df_eval

eval_ia = evaluar_ajustes(datos_ia, "Intervalo entre Arribos (IA)")
